const SITE = "https://www.mattsilverman.xyz/operator/proposal-"  // + slug: the link clients receive
const LIMITS = { name: 120, email: 200, phone: 40, note: 4000 }

const str = (v, max) => (typeof v === "string" ? v.trim().slice(0, max) : "")
const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c])
const rt = (s) => ({ rich_text: s ? [{ text: { content: String(s).slice(0, 2000) } }] : [] })
const json = (body, status = 200) =>
  new Response(JSON.stringify(body), { status, headers: { "Content-Type": "application/json", "Cache-Control": "no-store" } })

async function logToNotion(env, d) {
  const res = await fetch("https://api.notion.com/v1/pages", {
    method: "POST",
    headers: { Authorization: `Bearer ${env.NOTION_TOKEN}`, "Notion-Version": "2022-06-28", "Content-Type": "application/json" },
    body: JSON.stringify({
      parent: { database_id: env.NOTION_PROPOSALS_DATABASE },
      properties: {
        Name: { title: [{ text: { content: `${d.client} · ${d.name}` } }] },
        Client: { select: { name: d.client } },
        Pick: { select: { name: d.pick } },
        "Their notes": rt(d.note),
        "Contact name": rt(d.name),
        ...(d.email ? { Email: { email: d.email } } : {}),
        ...(d.phone ? { Phone: { phone_number: d.phone } } : {}),
        Proposal: { url: d.url },
        Received: { date: { start: new Date().toISOString() } },
        Stage: { status: { name: "Not started" } },
      },
    }),
  })
  if (!res.ok) throw new Error(`notion ${res.status}: ${await res.text()}`)
}

async function mail(env, d) {
  const rows = [["Client", d.client], ["Pick", d.pick], ["From", d.name], ["Email", d.email || "Not given"], ["Phone", d.phone || "Not given"]]
  const note = d.note || "No notes."
  const text = rows.map(([k, v]) => `${k.padEnd(10)}${v}`).join("\n") + `\n\nWhat they would change or keep\n------------------------------\n${note}\n\n${d.url}\n`
  const html = `<div style="font-family:ui-monospace,Menlo,monospace;font-size:14px;line-height:1.6;color:#11110f">
<p style="margin:0 0 18px;font-size:12px;letter-spacing:.14em;text-transform:uppercase;color:#69705b">Operator / proposal response</p>
<table cellpadding="0" cellspacing="0" style="border-collapse:collapse;margin-bottom:22px">${rows
    .map(([k, v]) => `<tr><td style="padding:4px 22px 4px 0;color:#6f6f64">${esc(k)}</td><td style="padding:4px 0">${esc(v)}</td></tr>`)
    .join("")}</table>
<div style="border-left:2px solid #e85d2a;padding:2px 0 2px 14px;white-space:pre-wrap;font-family:system-ui,sans-serif">${esc(note)}</div>
<p style="margin:22px 0 0;font-size:12px;color:#6f6f64"><a href="${esc(d.url)}" style="color:#11110f">Open the proposal</a></p></div>`
  const res = await fetch("https://api.resend.com/emails", {
    method: "POST",
    headers: { Authorization: `Bearer ${env.RESEND_API_KEY}`, "Content-Type": "application/json" },
    body: JSON.stringify({
      from: env.INQUIRY_FROM || "Operator <onboarding@resend.dev>",
      to: [env.INQUIRY_TO],
      ...(d.email ? { reply_to: [d.email] } : {}),
      subject: `Operator: ${d.client} picked ${d.pick}`,
      text, html,
    }),
  })
  if (!res.ok) throw new Error(`resend ${res.status}: ${await res.text()}`)
}

export async function onRequestPost({ request, env }) {
  let b = {}
  try { b = await request.json() } catch { b = {} }
  if (str(b.botcheck, 200)) return json({ ok: true })
  const elapsed = Number(b.elapsed)
  if (Number.isFinite(elapsed) && elapsed < 3000) return json({ ok: true })

  const c = CLIENTS[str(b.client, 40)]
  const pick = str(b.pick, 80)
  const d = {
    client: c ? c.name : "",
    url: c ? `${SITE}${c.slug}` : "",
    pick: c && c.picks.includes(pick) ? pick : "",
    note: str(b.note, LIMITS.note),
    name: str(b.name, LIMITS.name),
    email: str(b.email, LIMITS.email),
    phone: str(b.phone, LIMITS.phone),
  }
  const bad = []
  if (!d.client) bad.push("client")
  if (!d.pick) bad.push("pick")
  if (!d.name || /[\r\n]/.test(d.name)) bad.push("name")
  if (d.email && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(d.email)) bad.push("email")
  if (!d.email && !d.phone) bad.push("contact")
  if (bad.length) return json({ ok: false, error: "invalid", fields: bad }, 400)

  const notionReady = !!(env.NOTION_TOKEN && env.NOTION_PROPOSALS_DATABASE)
  const mailReady = !!(env.RESEND_API_KEY && env.INQUIRY_TO)
  if (!notionReady && !mailReady) {
    console.error("proposal: nothing configured", JSON.stringify(d))
    return json({ ok: false, error: "unconfigured" }, 503)
  }
  let filed = false, mailed = false
  if (notionReady) try { await logToNotion(env, d); filed = true } catch (e) { console.error("proposal: notion failed", String(e)) }
  if (mailReady) try { await mail(env, d); mailed = true } catch (e) { console.error("proposal: email failed", String(e)) }
  if (!filed && !mailed) {
    console.error("proposal: ALL CHANNELS FAILED", JSON.stringify(d))
    return json({ ok: false, error: "delivery" }, 502)
  }
  return json({ ok: true, filed, mailed })
}

